#!/usr/bin/env python3
"""
scan_docs.py - Mechanical inventory and integrity checks for repo documentation.

Handles the deterministic half of a documentation audit: finding every doc,
extracting the checkable claims out of them (links, paths, commands, versions,
env vars), and verifying the things that can be verified without judgment.

Emits JSON on stdout (or --out) plus a human summary on stderr.

Stdlib only. No network calls - external URLs are collected, never fetched.

Usage:
    python3 scan_docs.py [repo_root] [--out report.json] [--include-hidden]
    python3 scan_docs.py . --paths docs README.md
"""

import argparse
import json
import os
import re
import subprocess
import sys
from collections import defaultdict

DOC_EXTENSIONS = {".md", ".markdown", ".mdx", ".rst", ".txt", ".adoc"}

# Docs that are historical records or generated - flag, never rewrite.
PROTECTED_PATTERNS = re.compile(
    r"(^|/)(CHANGELOG|HISTORY|RELEASES?|NOTICE|LICENSE|LICENCE|COPYING|AUTHORS|CODE_OF_CONDUCT)",
    re.IGNORECASE,
)
GENERATED_MARKERS = re.compile(
    r"(do not edit|auto-?generated|generated by|@generated)", re.IGNORECASE
)

SKIP_DIRS = {
    ".git", "node_modules", "vendor", "dist", "build", "target",
    ".venv", "venv", "env", "__pycache__", ".mypy_cache", ".pytest_cache",
    ".next", ".nuxt", "site-packages", ".tox", "coverage", ".idea", ".vscode",
}

FENCE_RE = re.compile(r"^(\s*)(`{3,}|~{3,})\s*([A-Za-z0-9_+-]*)")
HEADING_RE = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")
SETEXT_RE = re.compile(r"^(=+|-+)\s*$")
INLINE_LINK_RE = re.compile(r"\[([^\]]*)\]\(\s*<?([^)\s>]+)>?(?:\s+\"[^\"]*\")?\s*\)")
REF_DEF_RE = re.compile(r"^\s{0,3}\[([^\]]+)\]:\s*<?(\S+)>?")
REF_USE_RE = re.compile(r"\[([^\]]*)\]\[([^\]]*)\]")
BARE_URL_RE = re.compile(r"<(https?://[^>\s]+)>")
HTML_LINK_RE = re.compile(r"<a\s+[^>]*href=[\"']([^\"']+)[\"']", re.IGNORECASE)
HTML_IMG_RE = re.compile(r"<img\s+[^>]*src=[\"']([^\"']+)[\"']", re.IGNORECASE)
INLINE_CODE_RE = re.compile(r"`[^`]*`")

VERSION_RE = re.compile(
    r"(?<![\w.])("
    r"v\d+\.\d+(?:\.\d+)?(?:-[A-Za-z0-9.]+)?"      # v1.2.3
    r"|\d+\.\d+\.\d+(?:-[A-Za-z0-9.]+)?"           # 1.2.3
    r"|[><=^~]=?\s?\d+(?:\.\d+)*"                  # >=3.9, ^18
    r")(?!\w)(?!\.\d)"                              # allow a sentence-ending period
)
VERSION_CONTEXT_RE = re.compile(
    r"(node|npm|pnpm|yarn|python|py|ruby|go|rust|java|php|docker|postgres|postgresql"
    r"|mysql|redis|django|flask|fastapi|react|next|vue|angular|typescript|ts"
    r"|kubernetes|k8s|terraform|dotnet|\.net)",
    re.IGNORECASE,
)
ENV_VAR_RE = re.compile(r"\b(?:export\s+)?([A-Z][A-Z0-9]{2,}(?:_[A-Z0-9]+)*)\s*=")
ENV_REF_RE = re.compile(
    r"(?:process\.env\.([A-Z][A-Z0-9_]*)"
    r"|os\.environ(?:\.get)?[\[(]\s*[\"']([A-Z][A-Z0-9_]*)[\"']"
    r"|ENV\[[\"']([A-Z][A-Z0-9_]*)[\"']\])"
)
PORT_RE = re.compile(r"(?:localhost|127\.0\.0\.1|0\.0\.0\.0|port\s*[:=]?\s*)[:\s]*(\d{2,5})", re.IGNORECASE)
# Markers are conventionally uppercase; matching case-insensitively would flag
# ordinary prose ("a todo list", "work in progress").
TODO_RE = re.compile(r"\b(TODO|FIXME|XXX|TBD|HACK|WIP)\b")
STALE_PHRASE_RE = re.compile(r"\b(coming soon|placeholder|lorem ipsum|to be written|tbd)\b", re.IGNORECASE)
SHELL_LANGS = {"bash", "sh", "shell", "zsh", "console", "shell-session", "terminal", ""}
NPM_SCRIPT_RE = re.compile(r"\b(?:npm|pnpm|yarn|bun)\s+run\s+([A-Za-z0-9:_-]+)")
MAKE_TARGET_RE = re.compile(r"\bmake\s+([A-Za-z0-9:_-]+)")


def run_git(root, *args):
    try:
        out = subprocess.run(
            ["git", "-C", root, *args],
            capture_output=True, text=True, timeout=30,
        )
        return out.stdout if out.returncode == 0 else None
    except (OSError, subprocess.SubprocessError):
        return None


def to_posix(path):
    """Forward slashes everywhere.

    Doc paths come from `git ls-files` (always '/'), but os.path.normpath and
    os.path.relpath emit '\\' on Windows. Without this the two never compare
    equal, which silently disables the orphan and cross-file anchor checks.
    """
    return path.replace(os.sep, "/")


def slugify(text, seen):
    """GitHub-style heading anchor."""
    text = re.sub(r"`([^`]*)`", r"\1", text)
    text = INLINE_LINK_RE.sub(r"\1", text)
    text = re.sub(r"[*_~]", "", text)
    slug = text.strip().lower()
    slug = re.sub(r"[^\w\s-]", "", slug, flags=re.UNICODE)
    slug = re.sub(r"[\s]+", "-", slug).strip("-")
    if not slug:
        slug = "section"
    count = seen[slug]
    seen[slug] += 1
    return slug if count == 0 else f"{slug}-{count}"


def find_docs(root, explicit_paths, include_hidden):
    """Prefer git-tracked files so we honor .gitignore; fall back to a walk."""
    docs = []
    if explicit_paths:
        for p in explicit_paths:
            full = os.path.join(root, p)
            if os.path.isfile(full):
                docs.append(to_posix(os.path.relpath(full, root)))
            elif os.path.isdir(full):
                for dirpath, dirnames, filenames in os.walk(full):
                    dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
                    for f in filenames:
                        if os.path.splitext(f)[1].lower() in DOC_EXTENSIONS:
                            docs.append(to_posix(os.path.relpath(os.path.join(dirpath, f), root)))
        return sorted(set(docs))

    tracked = run_git(root, "ls-files")
    if tracked is not None:
        for line in tracked.splitlines():
            if os.path.splitext(line)[1].lower() in DOC_EXTENSIONS:
                parts = line.split("/")
                if any(p in SKIP_DIRS for p in parts):
                    continue
                if not include_hidden and any(p.startswith(".") for p in parts[:-1]):
                    continue
                docs.append(line)
        return sorted(set(docs))

    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [
            d for d in dirnames
            if d not in SKIP_DIRS and (include_hidden or not d.startswith("."))
        ]
        for f in filenames:
            if os.path.splitext(f)[1].lower() in DOC_EXTENSIONS:
                docs.append(to_posix(os.path.relpath(os.path.join(dirpath, f), root)))
    return sorted(set(docs))


def strip_inline_code(line):
    return INLINE_CODE_RE.sub(" ", line)


def harvest_commands(doc, lang, body_lines, start_line):
    """Pull shell commands, npm scripts, make targets and env vars out of a code block."""
    for cmd_line in body_lines:
        if lang in SHELL_LANGS:
            c = cmd_line.strip().lstrip("$").strip()
            if c and not c.startswith("#"):
                doc["shell_commands"].append({"line": start_line, "cmd": c[:200]})
        harvest_task_refs(doc, cmd_line, start_line)
        for m in ENV_VAR_RE.finditer(cmd_line):
            doc["env_vars"].append({"line": start_line, "name": m.group(1)})
        for m in ENV_REF_RE.finditer(cmd_line):
            name = m.group(1) or m.group(2) or m.group(3)
            if name:
                doc["env_vars"].append({"line": start_line, "name": name})


def harvest_task_refs(doc, text, line_no):
    """npm/make references appear in prose and inline code too, not just fences."""
    for m in NPM_SCRIPT_RE.finditer(text):
        doc["npm_scripts"].append({"line": line_no, "script": m.group(1)})
    for m in MAKE_TARGET_RE.finditer(text):
        doc["make_targets"].append({"line": line_no, "target": m.group(1)})


def parse_doc(root, relpath):
    full = os.path.join(root, relpath)
    try:
        # utf-8-sig strips a leading BOM if present. Windows editors write them
        # routinely, and a BOM glued to line 1 stops the H1 regex matching.
        with open(full, encoding="utf-8-sig", errors="replace") as fh:
            raw = fh.read()
    except OSError as exc:
        return {"path": relpath, "error": str(exc)}

    lines = raw.split("\n")
    doc = {
        "path": relpath,
        "lines": len(lines),
        "words": len(raw.split()),
        "headings": [],
        "anchors": [],
        "links": [],
        "ref_defs": {},
        "ref_uses": [],
        "code_blocks": [],
        "shell_commands": [],
        "npm_scripts": [],
        "make_targets": [],
        "versions": [],
        "env_vars": [],
        "ports": [],
        "todos": [],
        "protected": bool(PROTECTED_PATTERNS.search(relpath)),
        "generated": bool(GENERATED_MARKERS.search(raw[:2000])),
        "has_h1": False,
        "trailing_whitespace_lines": 0,
    }

    seen_slugs = defaultdict(int)
    in_fence = False
    fence_marker = None
    fence_lang = None
    fence_start = 0
    fence_body = []
    in_frontmatter = False

    for idx, line in enumerate(lines, start=1):
        if idx == 1 and line.strip() in ("---", "+++"):
            in_frontmatter = True
            continue
        if in_frontmatter:
            if line.strip() in ("---", "+++"):
                in_frontmatter = False
            continue

        fence_match = FENCE_RE.match(line)
        if fence_match and not in_fence:
            in_fence = True
            fence_marker = fence_match.group(2)[0] * 3
            fence_lang = (fence_match.group(3) or "").lower()
            fence_start = idx
            fence_body = []
            continue
        if in_fence:
            closing = FENCE_RE.match(line)
            if closing and closing.group(2)[0] * 3 == fence_marker and not closing.group(3):
                body = "\n".join(fence_body)
                doc["code_blocks"].append({
                    "lang": fence_lang, "start_line": fence_start,
                    "end_line": idx, "lines": len(fence_body),
                    "empty": not body.strip(),
                })
                harvest_commands(doc, fence_lang, fence_body, fence_start)
                in_fence = False
                fence_marker = None
            else:
                fence_body.append(line)
            continue

        if line.rstrip() != line and line.strip():
            doc["trailing_whitespace_lines"] += 1

        heading = HEADING_RE.match(line)
        if heading:
            level = len(heading.group(1))
            text = heading.group(2).strip()
            anchor = slugify(text, seen_slugs)
            doc["headings"].append({"level": level, "text": text, "line": idx, "anchor": anchor})
            doc["anchors"].append(anchor)
            if level == 1:
                doc["has_h1"] = True
        elif (
            SETEXT_RE.match(line) and idx > 1
            and lines[idx - 2].strip() and not HEADING_RE.match(lines[idx - 2])
        ):
            level = 1 if line.strip().startswith("=") else 2
            text = lines[idx - 2].strip()
            anchor = slugify(text, seen_slugs)
            doc["headings"].append({"level": level, "text": text, "line": idx - 1, "anchor": anchor})
            doc["anchors"].append(anchor)
            if level == 1:
                doc["has_h1"] = True

        ref_def = REF_DEF_RE.match(line)
        if ref_def:
            doc["ref_defs"][ref_def.group(1).lower()] = ref_def.group(2)
            continue

        clean = strip_inline_code(line)

        for m in INLINE_LINK_RE.finditer(clean):
            doc["links"].append({"line": idx, "text": m.group(1), "target": m.group(2)})
        for m in BARE_URL_RE.finditer(clean):
            doc["links"].append({"line": idx, "text": "", "target": m.group(1)})
        for m in HTML_LINK_RE.finditer(line):
            doc["links"].append({"line": idx, "text": "", "target": m.group(1)})
        for m in HTML_IMG_RE.finditer(line):
            doc["links"].append({"line": idx, "text": "[img]", "target": m.group(1)})
        for m in REF_USE_RE.finditer(clean):
            doc["ref_uses"].append({"line": idx, "label": (m.group(2) or m.group(1)).lower()})

        for m in VERSION_RE.finditer(clean):
            # Attribute to the nearest keyword *before* the version, so
            # "node 18 and postgres 14" maps each number to the right subject.
            preceding = list(VERSION_CONTEXT_RE.finditer(clean[:m.start()]))
            subject = preceding[-1].group(1).lower() if preceding else None
            if subject is None:
                following = VERSION_CONTEXT_RE.search(clean[m.end():m.end() + 40])
                subject = following.group(1).lower() if following else None
            doc["versions"].append({
                "line": idx, "version": m.group(1).strip(),
                "subject": subject, "context": clean.strip()[:160],
            })
        harvest_task_refs(doc, line, idx)
        for m in ENV_REF_RE.finditer(line):
            name = m.group(1) or m.group(2) or m.group(3)
            if name:
                doc["env_vars"].append({"line": idx, "name": name})
        for m in PORT_RE.finditer(line):
            doc["ports"].append({"line": idx, "port": m.group(1), "context": line.strip()[:120]})
        for m in TODO_RE.finditer(clean):
            doc["todos"].append({"line": idx, "marker": m.group(1).upper(),
                                 "context": line.strip()[:120]})
        for m in STALE_PHRASE_RE.finditer(clean):
            doc["todos"].append({"line": idx, "marker": m.group(1).lower(),
                                 "context": line.strip()[:120]})

    if in_fence:
        doc["code_blocks"].append({
            "lang": fence_lang, "start_line": fence_start, "end_line": len(lines),
            "lines": len(fence_body), "empty": False, "unclosed": True,
        })
        harvest_commands(doc, fence_lang, fence_body, fence_start)

    # dedupe env vars by name
    seen_env = {}
    for e in doc["env_vars"]:
        seen_env.setdefault(e["name"], e)
    doc["env_vars"] = list(seen_env.values())

    return doc


def resolve_target(root, doc_path, target):
    """Split a link into (kind, filepath, anchor)."""
    if target.startswith(("http://", "https://", "//")):
        return "external", None, None
    if target.startswith(("mailto:", "tel:")):
        return "mailto", None, None
    if target.startswith("#"):
        return "anchor", doc_path, target[1:]
    file_part, _, anchor = target.partition("#")
    if not file_part:
        return "anchor", doc_path, anchor
    if file_part.startswith("/"):
        candidate = os.path.normpath(file_part.lstrip("/"))
    else:
        candidate = os.path.normpath(os.path.join(os.path.dirname(doc_path), file_part))
    return "internal", to_posix(candidate), anchor or None


def analyze(root, docs_data, all_docs):
    findings = []
    anchors_by_doc = {d["path"]: set(d.get("anchors", [])) for d in docs_data}
    incoming = defaultdict(set)

    def add(severity, check, path, line, message, detail=None):
        f = {"severity": severity, "check": check, "path": path,
             "line": line, "message": message}
        if detail:
            f["detail"] = [detail] if isinstance(detail, str) else list(detail)
        findings.append(f)

    for doc in docs_data:
        if doc.get("error"):
            add("high", "unreadable", doc["path"], None, f"Could not read file: {doc['error']}")
            continue
        path = doc["path"]

        for link in doc["links"]:
            kind, target_path, anchor = resolve_target(root, path, link["target"])
            if kind in ("external", "mailto"):
                continue
            if kind == "internal":
                full = os.path.join(root, target_path)
                if not os.path.exists(full):
                    add("high", "broken_link", path, link["line"],
                        f"Link target does not exist: {link['target']}")
                    continue
                incoming[target_path].add(path)
                if anchor and target_path in anchors_by_doc:
                    if anchor.lower() not in {a.lower() for a in anchors_by_doc[target_path]}:
                        add("medium", "broken_anchor", path, link["line"],
                            f"Anchor #{anchor} not found in {target_path}")
            elif kind == "anchor" and anchor:
                if anchor.lower() not in {a.lower() for a in anchors_by_doc.get(path, set())}:
                    add("medium", "broken_anchor", path, link["line"],
                        f"Anchor #{anchor} not found in this document")

        for use in doc["ref_uses"]:
            if use["label"] and use["label"] not in doc["ref_defs"]:
                add("medium", "undefined_reference", path, use["line"],
                    f"Reference-style link [{use['label']}] has no definition")

        used_labels = {u["label"] for u in doc["ref_uses"]}
        for label in doc["ref_defs"]:
            if label not in used_labels:
                add("low", "unused_reference", path, None,
                    f"Link definition [{label}] is defined but never used")

        for block in doc["code_blocks"]:
            if block.get("unclosed"):
                add("high", "unclosed_code_fence", path, block["start_line"],
                    "Code fence opened but never closed - breaks rendering below this point")
            elif block["empty"]:
                add("low", "empty_code_block", path, block["start_line"], "Empty code block")
            elif not block["lang"]:
                add("low", "unlabeled_code_block", path, block["start_line"],
                    "Code block has no language tag (no syntax highlighting)")

        for todo in doc["todos"]:
            add("medium", "unfinished_content", path, todo["line"],
                f"{todo['marker']} marker in published docs", todo["context"])

        if not doc["has_h1"] and doc["lines"] > 5 and not doc["generated"]:
            add("low", "missing_h1", path, 1, "Document has no top-level heading")

        levels = [h["level"] for h in doc["headings"]]
        for i in range(1, len(levels)):
            if levels[i] - levels[i - 1] > 1:
                h = doc["headings"][i]
                add("low", "heading_skip", path, h["line"],
                    f"Heading level jumps from h{levels[i-1]} to h{levels[i]}")

        titles = defaultdict(list)
        for h in doc["headings"]:
            titles[h["text"].strip().lower()].append(h["line"])
        for title, occurrences in titles.items():
            if len(occurrences) > 1:
                add("low", "duplicate_heading", path, occurrences[1],
                    f"Heading '{title}' appears {len(occurrences)} times (ambiguous anchors)")

    # Orphan docs: not linked from anywhere and not an obvious entry point.
    entry_points = {
        "readme.md", "readme.rst", "readme.txt", "index.md", "index.rst",
        "summary.md", "skill.md", "contributing.md", "security.md",
        "mkdocs.yml", "_sidebar.md", "toc.md",
    }
    for doc in docs_data:
        path = doc["path"]
        base = os.path.basename(path).lower()
        if base in entry_points or doc.get("protected"):
            continue
        if not incoming.get(path):
            add("medium", "orphan_doc", path, None,
                "No other document links here - readers may never find it")

    # Cross-document version conflicts on the same subject.
    by_subject = defaultdict(list)
    for doc in docs_data:
        # Changelogs and generated files legitimately list many versions.
        if doc.get("protected") or doc.get("generated"):
            continue
        for v in doc.get("versions", []):
            if v["subject"]:
                by_subject[v["subject"]].append({
                    "path": doc["path"], "line": v["line"],
                    "version": v["version"], "context": v["context"],
                })
    for subject, mentions in sorted(by_subject.items()):
        distinct = {m["version"] for m in mentions}
        if len(distinct) > 1:
            locations = [f"{m['path']}:{m['line']} -> {m['version']}" for m in mentions]
            add("high", "version_conflict", None, None,
                f"'{subject}' is documented with conflicting versions: {', '.join(sorted(distinct))}",
                locations)

    # Env vars documented in only one place - candidates for undocumented drift.
    env_locations = defaultdict(set)
    for doc in docs_data:
        for e in doc.get("env_vars", []):
            env_locations[e["name"]].add(doc["path"])

    port_map = defaultdict(set)
    for doc in docs_data:
        for p in doc.get("ports", []):
            port_map[p["port"]].add(f"{doc['path']}:{p['line']}")
    if len(port_map) > 1:
        add("medium", "port_inconsistency", None, None,
            f"Multiple ports referenced across docs: {', '.join(sorted(port_map))}",
            [f"{port}: {sorted(locs)}" for port, locs in sorted(port_map.items())])

    return findings, {
        "env_var_index": {k: sorted(v) for k, v in sorted(env_locations.items())},
        "npm_scripts_referenced": sorted({
            s["script"] for d in docs_data for s in d.get("npm_scripts", [])
        }),
        "make_targets_referenced": sorted({
            t["target"] for d in docs_data for t in d.get("make_targets", [])
        }),
        "external_links": sorted({
            l["target"] for d in docs_data for l in d.get("links", [])
            if l["target"].startswith(("http://", "https://"))
        }),
    }


def git_staleness(root, docs):
    """Compare each doc's last commit date against the repo's."""
    info = {}
    head_date = run_git(root, "log", "-1", "--format=%at")
    head_ts = int(head_date.strip()) if head_date and head_date.strip() else None
    for path in docs:
        out = run_git(root, "log", "-1", "--format=%at|%ad|%an", "--date=short", "--", path)
        if not out or not out.strip():
            info[path] = {"last_commit": None, "note": "untracked or no history"}
            continue
        ts, date, author = (out.strip().split("|") + ["", ""])[:3]
        try:
            ts_int = int(ts)
        except ValueError:
            continue
        entry = {"last_commit_date": date, "last_author": author}
        if head_ts:
            entry["days_behind_head"] = round((head_ts - ts_int) / 86400, 1)
        info[path] = entry
    return info


def main():
    ap = argparse.ArgumentParser(description="Inventory and check repo documentation.")
    ap.add_argument("root", nargs="?", default=".", help="Repo root (default: cwd)")
    ap.add_argument("--out", help="Write JSON report here (default: stdout)")
    ap.add_argument("--paths", nargs="*", help="Limit to these files/dirs")
    ap.add_argument("--include-hidden", action="store_true", help="Include dotted directories")
    ap.add_argument("--no-git", action="store_true", help="Skip git staleness lookup")
    args = ap.parse_args()

    root = os.path.abspath(args.root)
    if not os.path.isdir(root):
        print(f"error: {root} is not a directory", file=sys.stderr)
        return 2

    docs = find_docs(root, args.paths, args.include_hidden)
    if not docs:
        print("No documentation files found.", file=sys.stderr)
        json.dump({"root": root, "docs": [], "findings": []}, sys.stdout, indent=2)
        return 0

    docs_data = [parse_doc(root, d) for d in docs]
    findings, indexes = analyze(root, docs_data, docs)
    staleness = {} if args.no_git else git_staleness(root, docs)

    order = {"high": 0, "medium": 1, "low": 2}
    findings.sort(key=lambda f: (order.get(f["severity"], 3), f.get("path") or "", f.get("line") or 0))

    report = {
        "root": root,
        "doc_count": len(docs),
        "docs": docs_data,
        "findings": findings,
        "indexes": indexes,
        "staleness": staleness,
        "summary": {
            "total_findings": len(findings),
            "by_severity": {
                s: sum(1 for f in findings if f["severity"] == s)
                for s in ("high", "medium", "low")
            },
            "by_check": {
                c: sum(1 for f in findings if f["check"] == c)
                for c in sorted({f["check"] for f in findings})
            },
            "protected_docs": [d["path"] for d in docs_data if d.get("protected")],
            "generated_docs": [d["path"] for d in docs_data if d.get("generated")],
            "total_words": sum(d.get("words", 0) for d in docs_data),
        },
    }

    payload = json.dumps(report, indent=2)
    if args.out:
        with open(args.out, "w", encoding="utf-8") as fh:
            fh.write(payload)
    else:
        print(payload)

    s = report["summary"]
    print(f"\nScanned {len(docs)} docs ({s['total_words']} words)", file=sys.stderr)
    print(f"Findings: {s['total_findings']} "
          f"(high {s['by_severity']['high']}, "
          f"medium {s['by_severity']['medium']}, "
          f"low {s['by_severity']['low']})", file=sys.stderr)
    for check, count in sorted(s["by_check"].items(), key=lambda x: -x[1]):
        print(f"  {count:>4}  {check}", file=sys.stderr)
    if s["protected_docs"]:
        print(f"Protected (do not rewrite): {', '.join(s['protected_docs'])}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
